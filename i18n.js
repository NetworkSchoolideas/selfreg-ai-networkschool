function getLang() {
  const params = new URLSearchParams(window.location.search);
  const fromUrl = params.get("lang");
  if (fromUrl === "en" || fromUrl === "ru") return fromUrl;
  return localStorage.getItem("selfreg_lang") || "ru";
}

function setLang(lang) {
  localStorage.setItem("selfreg_lang", lang);
  const t = translations[lang];
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (t[key]) node.textContent = t[key];
  });
  document.querySelectorAll("[data-src-ru][data-src-en]").forEach((node) => {
    const src = node.getAttribute(`data-src-${lang}`);
    const alt = node.getAttribute(`data-alt-${lang}`);
    if (src) node.setAttribute("src", src);
    if (alt) node.setAttribute("alt", alt);
    if (node.tagName === "VIDEO" || node.tagName === "AUDIO") {
      node.pause();
      node.load();
    }
  });
  document.querySelectorAll("[data-lang-button]").forEach((node) => {
    const active = node.getAttribute("data-lang-button") === lang;
    node.classList.toggle("active", active);
    node.setAttribute("aria-pressed", String(active));
  });
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-lang-button]").forEach((button) => {
    button.addEventListener("click", () => setLang(button.getAttribute("data-lang-button")));
  });
  setLang(getLang());
});























